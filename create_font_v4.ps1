# Create proper 12x12 font data
# Each character: 12 rows, each row is 16 bits (left 12 bits visible)

function CreateChar {
    param([string[]]$rows)
    $result = @()
    foreach ($row in $rows) {
        $bits = ""
        for ($i = 0; $i -lt $row.Length; $i++) {
            if ($row[$i] -eq '#') {
                $bits += "1"
            } else {
                $bits += "0"
            }
        }
        # Pad to 16 bits on the right
        while ($bits.Length -lt 16) {
            $bits += "0"
        }
        $value = [Convert]::ToInt32($bits, 2)
        $result += "    dw 0x$('{0:X4}' -f $value)"
    }
    return $result
}


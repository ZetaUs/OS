$charOrder = @('N', 'o', 'v', 'a', ' ', 'O', 'S', 'W', 'e', 'l', 'c', 'm', 'U', 's', 'r', 'n', ':', 'P', 'w', 'd', 'L', 'g', 'i')

foreach ($char in $charOrder) {
    $charName = if ($char -eq ' ') { 'space' } else { "'$char'" }
    $output += "    ; $charName"
    foreach ($row in $font[$char]) {
        $output += "    dw $row"
    }
    $output += ""
}

$output += "    ; Terminator"
$output += "    dw 0x0000"


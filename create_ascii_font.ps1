        $value = [Convert]::ToInt32($row.Substring(2), 16)
        $binary = [Convert]::ToString($value, 2).PadLeft(16, '0').Substring(0, 12)
        $visual = $binary.Replace('0', '.').Replace('1', '#')
        Write-Host "  $visual"
    }
}
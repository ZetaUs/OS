# Create proper 12x12 ASCII font data
# Each character: 12 rows, each row is 16 bits (left 12 bits visible)

$font = @{}

# Helper: create a 12x12 bitmap from a visual pattern
function CreateChar {
    param([string[]]$rows)
    $result = @()
    foreach ($row in $rows) {
        $bits = ""
        for ($i = 0; $i -lt 12; $i++) {
            if ($i -lt $row.Length -and $row[$i] -eq '#') {
                $bits += "1"
            } else {
                $bits += "0"
            }
        }
        # Pad to 16 bits
        $bits = $bits.PadRight(16, '0')
        $value = [Convert]::ToInt32($bits, 2)
        $result += "0x$('{0:X4}' -f $value)"
    }
    return $result
}


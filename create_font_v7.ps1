# Create proper 12x12 font data with correct bit alignment
# Each character: 12 rows, each row is 16 bits
# Left 12 bits are visible (bits 15-4), right 4 bits are padding (bits 3-0)
# IMPORTANT: '#' maps to bit 15 (leftmost), '.' maps to bit 0

function CreateChar {
    param([string[]]$rows)
    $result = @()
    foreach ($row in $rows) {
        # Build binary string from left to right
        # Leftmost char -> bit 15 (MSB), Rightmost char -> bit 4
        $bits = ""
        for ($i = 0; $i -lt $row.Length; $i++) {
            if ($row[$i] -eq '#') {
                $bits += "1"
            } else {
                $bits += "0"
            }
        }
        # Pad to 16 bits on the right (4 bits padding for bits 3-0)
        while ($bits.Length -lt 16) {
            $bits += "0"
        }
        $value = [Convert]::ToInt32($bits, 2)
        $result += "    dw 0x$('{0:X4}' -f $value)"
    }
    return $result
}


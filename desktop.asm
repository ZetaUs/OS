bits 32

; VGA framebuffer address
VGA_MEMORY equ 0xA0000
SCREEN_WIDTH equ 320

; Colors
COLOR_BG equ 1
COLOR_TEXT equ 15

global ___desktop_screen

section .text

___desktop_screen:
    push ebp
    mov ebp, esp
    push ebx
    push ecx
    push edx
    push esi
    push edi
    
    ; Clear screen with blue background
    mov edi, VGA_MEMORY
    mov ecx, 320 * 200
    mov al, COLOR_BG
    rep stosb
    
    ; Draw "Nova OS Desktop" text at (10, 10)
    mov edi, VGA_MEMORY
    mov eax, 10
    mov ebx, 10
    imul ebx, SCREEN_WIDTH
    add edi, ebx
    add edi, eax
    
    mov esi, desktop_text
    mov edx, COLOR_TEXT
    
.print_loop:
    lodsb
    test al, al
    jz .done
    
    push esi
    push edi
    push edx
    
    call draw_char_8x8
    
    pop edx
    pop edi
    pop esi
    
    add edi, 8
    jmp .print_loop
    
.done:
    pop edi
    pop esi
    pop edx
    pop ecx
    pop ebx
    pop ebp
    ret

; Function: draw_char_8x8
; Input: al = character, edi = vram pointer, edx = color
draw_char_8x8:
    push ebx
    push ecx
    push edx
    push esi
    
    ; Get font pointer
    movzx ebx, al
    shl ebx, 3  ; multiply by 8 (8 bytes per char)
    add ebx, font_data
    
    mov ecx, 8  ; 8 rows
.draw_row:
    push ecx
    mov cl, [ebx]
    mov ecx, 8  ; 8 columns
.draw_col:
    test cl, 0x80
    jz .skip
    mov byte [edi], dl
.skip:
    shl cl, 1
    inc edi
    dec ecx
    jnz .draw_col
    
    pop ecx
    add edi, SCREEN_WIDTH
    sub edi, 8
    inc ebx
    dec ecx
    jnz .draw_row
    
    pop esi
    pop edx
    pop ecx
    pop ebx
    ret


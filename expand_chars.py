deng = [0x0A, 0x40, 0x7A, 0xA0, 0x49, 0x40, 0x28, 0x80, 0x1F, 0xC0, 0x20, 0x30,
        0xDF, 0xA0, 0x10, 0x80, 0x1F, 0x80, 0x09, 0x00, 0x09, 0x20, 0xFF, 0xF0]
lu = [0x3F, 0x80, 0x00, 0x80, 0x3F, 0x80, 0x00, 0x80, 0xFF, 0xF0, 0x24, 0x40,
      0x16, 0x80, 0x0D, 0x00, 0x34, 0x80, 0xC4, 0x70, 0x14, 0x20, 0x08, 0x00]

def expand(data):
    result = []
    for i in range(12):
        b1 = data[i*2]
        b2 = data[i*2+1]
        for j in range(12):
            if j < 8:
                bit = (b1 >> (7-j)) & 1
            else:
                bit = (b2 >> (15-j)) & 1
            result.append(bit)
    return result

deng_exp = expand(deng)
lu_exp = expand(lu)

print('deng_expanded:')
print(', '.join(str(x) for x in deng_exp))
print()
print('lu_expanded:')
print(', '.join(str(x) for x in lu_exp))
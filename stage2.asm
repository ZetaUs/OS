    ; Set video mode 0x13 (320x200, 256 colors)
    mov ax, 0x0013
    int 0x10
    
    ; === Enable VGA Chain-4 Mode ===
    ; This is REQUIRED for linear pixel access in mode 0x13
    
    ; Reset Sequencer
    mov dx, 0x03C4
    mov al, 0x00
    out dx, al
    inc dx
    mov al, 0x01
    out dx, al
    
    ; Enable Chain-4 in Sequencer Memory Mode (Index 0x04)
    mov dx, 0x03C4
    mov al, 0x04
    out dx, al
    inc dx
    mov al, 0x0E       ; Bit 3=1 (Chain4)
    out dx, al
    
    ; Enable Chain-4 in Graphics Controller Mode (Index 0x05)
    mov dx, 0x03CE
    mov al, 0x05
    out dx, al
    inc dx
    mov al, 0x08       ; Bit 3=1 (Chain4), NOT bit 6!
    out dx, al
    
    ; Clear Sequencer Reset
    mov dx, 0x03C4
    mov al, 0x00
    out dx, al
    inc dx
    mov al, 0x03
    out dx, al
    

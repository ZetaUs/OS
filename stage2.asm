init_palette:
    push ax
    push bx
    push cx
    push dx
    
    mov dx, 0x03C8
    mov al, 0
    out dx, al
    inc dx
    
    ; Color 0: Black
    xor al, al
    out dx, al
    out dx, al
    out dx, al
    
    ; Color 1: Dark Blue (background)
    xor al, al
    out dx, al
    xor al, al
    out dx, al
    mov al, 42
    out dx, al
    
    ; Color 2: Gray (loading bar background)
    mov al, 32
    out dx, al
    out dx, al
    out dx, al
    
    ; Color 3: Light Blue (loading bar)
    mov al, 21
    out dx, al
    mov al, 42
    out dx, al
    mov al, 63
    out dx, al
    
    ; Color 4: Dark Gray (login box)
    mov al, 21
    out dx, al
    out dx, al
    out dx, al
    

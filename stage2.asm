; ============================================================
; Draw 160x160 image from memory to VRAM
; Input: SI=Source segment, DI=Dest segment (VRAM)
;        CX=X position, DX=Y position
;        BX=Width (160), BP=Height (160)
; ============================================================
draw_image_160x160:
    push ax
    push bx
    push cx
    push dx
    push si
    push di
    push bp
    push es
    push ds
    
    ; Save source segment
    mov [img_src_seg], si
    ; Save dest segment (VRAM)
    mov [img_dst_seg], di
    ; Save X position
    mov [img_x], cx
    ; Save Y position
    mov [img_y], dx
    ; Save width
    mov [img_width], bx
    ; Save height
    mov [img_height], bp
    
    ; Set DS to source segment
    mov ds, [img_src_seg]
    ; Set ES to VRAM
    mov es, [img_dst_seg]
    
    ; Source offset = 0
    xor si, si
    
    ; Draw row by row
    mov bp, [img_height]

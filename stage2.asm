; ============================================================
; Draw a filled rectangle
; Input: CX=X, DX=Y, BX=Width, SI=Height, AL=Color
; ============================================================
draw_rect:
    push bp
    push si
    push di
    push es
    
    ; Save parameters to memory variables
    mov [rect_x], cx
    mov [rect_y], dx
    mov [rect_width], bx
    mov [rect_height], si
    mov [rect_color], al
    
    ; Set ES to VRAM
    mov ax, 0xA000
    mov es, ax
    
    ; Initialize row counter
    mov bp, dx           ; BP = current Y
    mov si, [rect_height] ; SI = height counter
    
draw_rect_row:
    ; Calculate VRAM offset: Y * 320 + X
    ; Use a simpler approach: Y * 320 = Y * 256 + Y * 64
    mov ax, bp           ; AX = Y
    mov di, ax           ; DI = Y
    shl di, 8            ; DI = Y * 256
    mov dx, ax           ; DX = Y
    shl dx, 6            ; DX = Y * 64
    add di, dx           ; DI = Y * 320
    add di, [rect_x]     ; DI = Y * 320 + X
    
    ; Draw one row using rep stosb
    mov cx, [rect_width]
    mov al, [rect_color]
    rep stosb
    
    inc bp               ; Y++
    dec si               ; height--
    jnz draw_rect_row
    
    pop es
    pop di
    pop si
    pop bp
    ret


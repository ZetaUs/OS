start:
    cli
    xor ax, ax
    mov ds, ax
    mov es, ax
    mov ss, ax
    mov sp, 0x7000
    sti
    
    mov ax, 0x07E0
    mov ds, ax
    
    mov ax, 0x0013
    int 0x10
    
    mov ax, 0xA000
    mov es, ax
    xor di, di
    mov cx, 64000
    mov al, 1
    rep stosb
    
    call init_palette
    
    mov cx, 40
    mov dx, 30
    mov bx, 240
    mov si, 140
    mov al, 2
    call draw_rect
    
    mov cx, 55
    mov dx, 80
    mov bx, 210
    mov si, 18
    mov al, 3
    call draw_rect
    
    mov cx, 55
    mov dx, 115
    mov bx, 210
    mov si, 18
    mov al, 3
    call draw_rect
    
    mov cx, 100
    mov dx, 142
    mov bx, 120
    mov si, 20
    mov al, 4
    call draw_rect
    
    ; Draw title "Nova OS" using 8x8 font
    mov si, title_msg
    mov bp, 110
    mov dx, 10
    call draw_string_8x8
    
    ; DEBUG: Yellow pixel at (110, 10) to verify position
    mov ax, 0xA000
    mov es, ax
    mov di, 10 * 320 + 110
    mov al, 14
    stosb
    
    ; Draw "Welcome"
    mov si, welcome_msg
    mov bp, 115
    mov dx, 55
    call draw_string_8x8
    
    ; Draw "Username:"
    mov si, username_msg
    mov bp, 55
    mov dx, 65
    call draw_string_8x8
    
    ; Draw "Password:"
    mov si, password_msg
    mov bp, 55
    mov dx, 100
    call draw_string_8x8
    
    ; Draw "Login"
    mov si, login_msg
    mov bp, 125
    mov dx, 148
    call draw_string_8x8
    
    call init_mouse
    
    mov ax, [mouse_x]
    mov [mouse_prev_x], ax
    mov ax, [mouse_y]
    mov [mouse_prev_y], ax
    
main_loop:
    mov ax, [mouse_x]
    mov [mouse_prev_x], ax
    mov ax, [mouse_y]
    mov [mouse_prev_y], ax
    
    call read_mouse
    
    mov ax, [mouse_x]
    mov bx, [mouse_prev_x]
    cmp ax, bx
    jne mouse_moved
    mov ax, [mouse_y]
    mov bx, [mouse_prev_y]
    cmp ax, bx
    je main_loop
    
mouse_moved:
    call draw_mouse_cursor
    
    mov cx, 500
delay_loop:
    loop delay_loop
    
    jmp main_loop

halt_s2:
    hlt
    jmp halt_s2

init_palette:
    push ax
    push bx
    push cx
    push dx
    
    mov dx, 0x03C8
    mov al, 0
    out dx, al
    inc dx
    
    xor al, al
    out dx, al
    out dx, al
    out dx, al
    
    mov al, 0
    out dx, al
    mov al, 0
    out dx, al
    mov al, 42
    out dx, al
    
    mov al, 32
    out dx, al
    mov al, 32
    out dx, al
    mov al, 32
    out dx, al
    
    mov al, 42
    out dx, al
    mov al, 42
    out dx, al
    mov al, 42
    out dx, al
    
    mov al, 63
    out dx, al
    xor al, al
    out dx, al
    xor al, al
    out dx, al
    
    mov al, 21
    out dx, al
    mov al, 21
    out dx, al
    mov al, 21
    out dx, al
    
    xor al, al
    out dx, al
    mov al, 63
    out dx, al
    xor al, al
    out dx, al
    
    mov al, 63
    out dx, al
    mov al, 63
    out dx, al
    mov al, 63
    out dx, al
    
    pop dx
    pop cx
    pop bx
    pop ax
    ret

draw_rect:
    push bp
    push si
    push di
    push es
    mov [rect_x], cx
    mov [rect_y], dx
    mov [rect_width], bx
    mov [rect_height], si
    mov [rect_color], al
    mov ax, 0xA000
    mov es, ax
    mov dx, [rect_y]
draw_rect_row:
    mov cx, [rect_x]
    mov bx, [rect_width]
draw_rect_col:
    push dx
    push cx
    mov ax, 320
    mul dx
    pop cx
    add ax, cx
    mov di, ax
    mov al, [rect_color]
    stosb
    pop dx
    inc cx
    dec bx
    jnz draw_rect_col
    inc dx
    dec word [rect_height]
    jnz draw_rect_row
    pop es
    pop di
    pop si
    pop bp
    ret

draw_string_8x8:
    push bx
    push cx
    push dx
    push si
    push di
    push bp
    mov [str_x], bp
    mov [str_y], dx
    
draw_str_loop:
    lodsb
    test al, al
    jz draw_str_done
    push si
    mov bp, [str_x]
    mov dx, [str_y]
    call draw_char_8x8
    pop si
    add word [str_x], 8
    jmp draw_str_loop
draw_str_done:
    pop bp
    pop di
    pop si
    pop dx
    pop cx
    pop bx
    ret

draw_char_8x8:
    push bx
    push cx
    push dx
    push si
    push di
    push bp
    push es
    
    mov [char_x], bp
    mov [char_y], dx
    
    mov bl, al
    mov bh, 0
    shl bx, 3
    
    mov si, font_8x8
    add si, bx
    
    mov ax, 0xA000
    mov es, ax
    mov cx, 8
    mov [char_row], cx
    xor bx, bx
    
draw_char_row:
    mov cl, [si]      ; CL = 字体行数据（保存）
    inc si
    mov dx, [char_y]
    add dx, bx
    mov bp, dx
    mov ax, 320
    mul word [bp]     ; AX = 320 * Y坐标
    mov di, ax
    add di, [char_x]
    mov ch, 8
    mov dl, cl        ; DL = 字体行数据
    
draw_char_pixel:
    test dl, 0x80
    jz skip_pixel
    mov al, 7
    stosb
    jmp next_pixel
skip_pixel:
    inc di
next_pixel:
    shl dl, 1
    dec ch
    jnz draw_char_pixel
    inc bx
    dec word [char_row]
    jnz draw_char_row
    
    pop es
    pop bp
    pop di
    pop si
    pop dx
    pop cx
    pop bx
    ret

init_mouse:
    push ax
    push bx
    push cx
    push dx
    
    mov ax, 0
    int 0x33
    
    mov ax, 1
    int 0x33
    
    mov ax, 7
    mov cx, 0
    mov dx, 319
    int 0x33
    
    mov ax, 8
    mov cx, 0
    mov dx, 199
    int 0x33
    
    pop dx
    pop cx
    pop bx
    pop ax
    ret

read_mouse:
    push ax
    push bx
    push cx
    push dx
    
    mov ax, 3
    int 0x33
    
    mov [mouse_x], cx
    mov [mouse_y], dx
    mov [mouse_buttons], bl
    
    pop dx
    pop cx
    pop bx
    pop ax
    ret

draw_mouse_cursor:
    push ax
    push bx
    push cx
    push dx
    push di
    push es
    push si
    
    mov ax, 0xA000
    mov es, ax
    
    mov si, [mouse_y]
    mov di, [mouse_x]
    
    push si
    push di
    sub di, 2
    call draw_cursor_pixel_at
    inc di
    call draw_cursor_pixel_at
    inc di
    call draw_cursor_pixel_at
    inc di
    call draw_cursor_pixel_at
    inc di
    call draw_cursor_pixel_at
    pop di
    pop si
    
    push si
    push di
    sub si, 2
    call draw_cursor_pixel_at
    inc si
    call draw_cursor_pixel_at
    inc si
    call draw_cursor_pixel_at
    inc si
    call draw_cursor_pixel_at
    inc si
    call draw_cursor_pixel_at
    pop di
    pop si
    
    pop si
    pop es
    pop di
    pop dx
    pop cx
    pop bx
    pop ax
    ret

draw_cursor_pixel_at:
    push ax
    push bx
    push cx
    push dx
    
    mov dx, si
    mov cx, di
    
    cmp dx, 199
    ja draw_cursor_pixel_at_done
    cmp cx, 319
    ja draw_cursor_pixel_at_done
    
    mov ax, 320
    mul dx
    add ax, cx
    mov bx, ax
    
    mov di, bx
    mov al, 7
    stosb
    
draw_cursor_pixel_at_done:
    pop dx
    pop cx
    pop bx
    pop ax
    ret


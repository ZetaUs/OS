rect_color: db 0

; ============================================================
; Draw an 8x8 character using embedded font
; Input: AL=Character, BP=X, DX=Y
; DS=0x0000 (code segment), ES will be set to VRAM
; ============================================================
draw_char_8x8:
    push ax
    push bx
    push cx
    push dx
    push si
    push di
    push es
    
    ; Save original X and Y
    mov [char_x], bp
    mov [char_y], dx
    
    ; Calculate font offset: (char - 0x20) * 8
    sub al, 0x20
    mov ah, 0
    mov si, ax
    shl si, 3            ; SI = (char - 0x20) * 8
    
    ; Set ES to VRAM for drawing
    mov ax, 0xA000
    mov es, ax
    
    ; Draw 8 rows
    mov cx, 8
    mov [char_row], cx
draw_char_row:
    ; Get font byte for this row from DS:SI (DS=0x0000)
    mov al, [si]
    inc si
    
    ; Calculate current Y position
    mov dx, [char_y]
    mov ax, 8
    sub ax, [char_row]   ; AX = current row (0-7)
    add dx, ax           ; DX = char_y + row
    
    ; Calculate VRAM offset for this row start
    mov bp, dx           ; Save Y in BP
    mov ax, 320
    mul bp               ; DX:AX = 320 * Y
    mov di, ax
    add di, [char_x]     ; DI = Y * 320 + X
    
    ; Draw 8 pixels for this row
    mov cx, 8
draw_char_pixel:
    push cx
    push ax
    
    ; Check if this bit is set
    test al, 0x80
    jz skip_pixel
    
    mov al, 7            ; White color
    stosb
    jmp next_pixel
    
skip_pixel:
    inc di               ; Skip this pixel
    
next_pixel:
    pop ax
    pop cx
    
    shl al, 1            ; Shift to next bit
    loop draw_char_pixel
    
    dec word [char_row]
    jnz draw_char_row
    
    pop es
    pop di
    pop si
    pop dx
    pop cx
    pop bx
    pop ax
    ret

char_x: dw 0
char_y: dw 0
char_row: dw 0

; ============================================================
; Draw a string using 8x8 font
; Input: SI=String pointer, BP=X, DX=Y
; ============================================================
draw_string_8x8:
    push ax
    push bx
    push cx
    push dx
    push si
    push di
    push bp
    
draw_str_loop:
    lodsb
    test al, al
    jz draw_str_done
    
    push si
    push bp
    push dx
    
    call draw_char_8x8
    
    pop dx
    pop bp
    add bp, 8            ; Move to next character position
    pop si
    
    jmp draw_str_loop
    
draw_str_done:
    pop bp
    pop di
    pop si
    pop dx
    pop cx
    pop bx
    pop ax
    ret

